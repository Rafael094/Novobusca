"""Private document storage abstraction (decision D2).

The application NEVER writes confidential documents to a public directory and
never trusts a client-supplied path. Physical keys are opaque and generated by
the server as ``documents/{tenant_id}/{document_id}``; the original filename is
kept only as display metadata.

Two backends are provided:

* ``LocalPrivateStorage`` — default for development/pilot; writes under
  ``settings.document_storage_path`` (outside any web-served directory) using a
  strict key whitelist and resolved-path containment checks.
* ``S3Storage`` — adapter for private object storage (S3/MinIO). It is **NOT
  operational until configured**; it raises ``StorageBackendNotConfigured``
  rather than silently succeeding, so the system never *pretends* it stored a
  confidential file.

The module also performs **content validation** (MIME sniffing via magic bytes)
and a size ceiling, both configurable.
"""

from __future__ import annotations

import hashlib
import os
import re
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from app.config import settings

# Allowed key shape: only the generated form. Anything else is rejected before
# ever touching the filesystem (defence in depth against traversal).
_KEY_RE = re.compile(r"^documents/[0-9a-fA-F-]{36}/[0-9a-fA-F-]{36}$")

# Magic-byte signatures for the allowed document types (decision A5: PDF/DOCX/
# images). Extension and declared MIME are NOT trusted — the real bytes decide.
_MAGIC: tuple[tuple[bytes, str], ...] = (
    (b"%PDF-", "application/pdf"),
    (b"\x89PNG\r\n\x1a\n", "image/png"),
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"GIF87a", "image/gif"),
    (b"GIF89a", "image/gif"),
    # OOXML (.docx/.xlsx/.pptx) and ODF are ZIP containers.
    (b"PK\x03\x04", "application/zip"),
)

ALLOWED_MIME_TYPES: frozenset[str] = frozenset(
    {
        "application/pdf",
        "image/png",
        "image/jpeg",
        "image/gif",
        "application/zip",  # docx/xlsx/pptx/odt (validated by magic bytes)
    }
)


class StorageError(Exception):
    """Base class for storage failures surfaced to the API layer."""


class StorageBackendNotConfigured(StorageError):
    """Raised when a backend is selected but has no real configuration."""


class UnsupportedFileType(StorageError):
    """Raised when the uploaded bytes do not match an allowed type."""


class FileTooLarge(StorageError):
    """Raised when the payload exceeds the configured ceiling."""


@dataclass(frozen=True)
class StoredObject:
    key: str
    size_bytes: int
    sha256: str
    detected_mime: str


class StorageBackend(Protocol):
    def put(self, key: str, data: bytes) -> StoredObject: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


def sniff_mime(data: bytes) -> str | None:
    """Return the MIME type inferred from the leading magic bytes (or ``None``)."""
    for signature, mime in _MAGIC:
        if data.startswith(signature):
            return mime
    return None


def validate_upload(data: bytes) -> str:
    """Validate size + real content type; return the detected MIME type.

    Raises :class:`FileTooLarge` / :class:`UnsupportedFileType`. An empty file is
    rejected (it carries no usable content and no signature).
    """
    if not data:
        raise UnsupportedFileType("Arquivo vazio não é aceito.")
    if len(data) > settings.document_max_size_bytes:
        raise FileTooLarge(
            f"Arquivo excede o limite de {settings.document_max_size_mb} MB."
        )
    detected = sniff_mime(data)
    if detected is None or detected not in ALLOWED_MIME_TYPES:
        raise UnsupportedFileType(
            "Tipo de arquivo não permitido (aceitos: PDF, DOCX/XLSX, imagens)."
        )
    return detected


def build_storage_key(tenant_id: uuid.UUID, document_id: uuid.UUID) -> str:
    return f"documents/{tenant_id}/{document_id}"


class LocalPrivateStorage:
    """Filesystem backend writing to a private directory outside static assets."""

    def __init__(self, root: Path | None = None) -> None:
        self._root = (root or settings.document_storage_path).resolve()
        self._root.mkdir(parents=True, exist_ok=True)

    def _path_for(self, key: str) -> Path:
        if not _KEY_RE.match(key):
            raise StorageError("Chave de armazenamento inválida.")
        candidate = (self._root / key).resolve()
        # The resolved path MUST stay inside the storage root (no traversal).
        if self._root != candidate and self._root not in candidate.parents:
            raise StorageError("Caminho de armazenamento inválido.")
        return candidate

    def put(self, key: str, data: bytes) -> StoredObject:
        detected = validate_upload(data)
        path = self._path_for(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha256(data).hexdigest()
        # Write to a sibling temp file then atomically replace: a partial write
        # can never leave a corrupt document behind.
        tmp = path.with_name(path.name + ".tmp")
        with open(tmp, "wb") as fh:
            fh.write(data)
        os.replace(tmp, path)
        return StoredObject(
            key=key, size_bytes=len(data), sha256=digest, detected_mime=detected
        )

    def get(self, key: str) -> bytes:
        path = self._path_for(key)
        if not path.is_file():
            raise StorageError("Documento não encontrado no armazenamento.")
        return path.read_bytes()

    def delete(self, key: str) -> None:
        path = self._path_for(key)
        if path.is_file():
            path.unlink()

    def exists(self, key: str) -> bool:
        try:
            return self._path_for(key).is_file()
        except StorageError:
            return False


class S3Storage:
    """Private object-storage adapter (S3/MinIO) — inert until configured.

    This adapter exists so the interface is stable and the production backend can
    be plugged in without touching the routers. It deliberately raises
    :class:`StorageBackendNotConfigured` because no bucket/credentials are
    provisioned (decision S1/D2-prod). It NEVER fakes a successful store.
    """

    def __init__(self) -> None:
        if not settings.storage_bucket:
            raise StorageBackendNotConfigured(
                "STORAGE_BACKEND=s3 selecionado, mas STORAGE_BUCKET não está "
                "configurado. Provisione o bucket privado antes de usar este backend."
            )
        raise StorageBackendNotConfigured(
            "Adaptador S3/MinIO preparado, porém não habilitado nesta implantação. "
            "Configure credenciais e o cliente boto3 para ativá-lo."
        )

    def put(self, key: str, data: bytes) -> StoredObject:  # pragma: no cover
        raise StorageBackendNotConfigured("S3 não configurado.")

    def get(self, key: str) -> bytes:  # pragma: no cover
        raise StorageBackendNotConfigured("S3 não configurado.")

    def delete(self, key: str) -> None:  # pragma: no cover
        raise StorageBackendNotConfigured("S3 não configurado.")

    def exists(self, key: str) -> bool:  # pragma: no cover
        return False


_backend: StorageBackend | None = None


def get_storage() -> StorageBackend:
    """Return the configured storage backend (cached per process)."""
    global _backend
    if _backend is None:
        backend_name = settings.storage_backend.strip().lower()
        if backend_name == "s3":
            _backend = S3Storage()
        else:
            _backend = LocalPrivateStorage()
    return _backend


def reset_storage_cache() -> None:
    """Drop the cached backend (used by tests / configuration reloads)."""
    global _backend
    _backend = None

